        title = "Ta prise · ${module.title}",
        steps = listOf(
            "Relis le critère de validation de l'objectif.",
            "Choisis un chant connu et travaille le passage qui le montre le mieux.",
            "Enregistre-toi dans un endroit calme, réécoute, puis envoie la prise qui te représente.",
        ),
        criteria = "Le responsable écoute ce que demande l'objectif, pas la qualité de l'enregistrement.",
        example = listOf(60, 62, 64, 65, 67),
    )
