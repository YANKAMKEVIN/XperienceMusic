package com.xperiencemusic.shared.domain.learning

import com.xperiencemusic.shared.domain.model.Instrument

/**
 * The singers' guided path: one module per objective of the programme that no microphone tier
 * validates. Sung activities are pitched from the singer's comfort note, so every voice gets its
 * own; the rest are lessons, listening and short questions. As for the piano, nothing here validates
 * an objective: the Admin++ does, from a take or in rehearsal.
 */
object SingerLearning {
    private fun lesson(id: String, title: String, instruction: String, explanation: String) =
        LearningActivity(id, title, LearningKind.LESSON, instruction, explanation)

    private fun choice(id: String, title: String, question: String, answer: String, choices: List<String>, explanation: String) =
        LearningActivity(id, title, LearningKind.CHOICE, question, explanation, answer = answer, choices = choices)

    private fun ear(id: String, title: String, question: String, example: List<Int>, answer: String, choices: List<String>, explanation: String) =
        LearningActivity(id, title, LearningKind.EAR, question, explanation, example = example, answer = answer, choices = choices)

    private fun sing(id: String, title: String, instruction: String, target: SingTarget, explanation: String) =
        LearningActivity(id, title, LearningKind.SING, instruction, explanation, sing = target)

    private fun practice(id: String, title: String, instruction: String, explanation: String) =
        LearningActivity(id, title, LearningKind.PRACTICE, instruction, explanation)

    private fun module(id: String, title: String, objectiveId: String, vararg activities: LearningActivity) =
        LearningModule(id, title, objectiveId, activities.toList(), Instrument.SINGER)

